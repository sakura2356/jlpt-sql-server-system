-- 依外鍵順序安全移除舊表（方便重複執行測試）
IF OBJECT_ID('dbo.Test_Details', 'U') IS NOT NULL DROP TABLE dbo.Test_Details;
IF OBJECT_ID('dbo.Tests', 'U') IS NOT NULL DROP TABLE dbo.Tests;
IF OBJECT_ID('dbo.Questions', 'U') IS NOT NULL DROP TABLE dbo.Questions;
IF OBJECT_ID('dbo.Users', 'U') IS NOT NULL DROP TABLE dbo.Users;
GO

-- ----------------------------------------------------------------------------
-- 1. Users（使用者表）
-- ----------------------------------------------------------------------------
CREATE TABLE dbo.Users (
    user_id INT IDENTITY(1,1) PRIMARY KEY,
    username NVARCHAR(50) NOT NULL,
    email VARCHAR(100) NOT NULL UNIQUE,
    target_level VARCHAR(5) NOT NULL,
    created_at DATETIME2 DEFAULT SYSDATETIME(),
    CONSTRAINT chk_user_level CHECK (target_level IN ('N1', 'N2', 'N3', 'N4', 'N5'))
);
GO

-- ----------------------------------------------------------------------------
-- 2. Questions（題庫母體表）
-- ----------------------------------------------------------------------------
CREATE TABLE dbo.Questions (
    question_id INT IDENTITY(1,1) PRIMARY KEY,
    level VARCHAR(5) NOT NULL,
    category NVARCHAR(20) NOT NULL,
    question_text NVARCHAR(MAX) NOT NULL,
    option_a NVARCHAR(255) NOT NULL,
    option_b NVARCHAR(255) NOT NULL,
    option_c NVARCHAR(255) NOT NULL,
    option_d NVARCHAR(255) NOT NULL,
    correct_answer CHAR(1) NOT NULL,
    explanation NVARCHAR(MAX) NOT NULL,
    CONSTRAINT chk_q_level CHECK (level IN ('N1', 'N2', 'N3', 'N4', 'N5')),
    CONSTRAINT chk_q_answer CHECK (correct_answer IN ('A', 'B', 'C', 'D'))
);
GO

-- ----------------------------------------------------------------------------
-- 3. Tests（測驗總表，1:N 關聯於 Users）
-- ----------------------------------------------------------------------------
CREATE TABLE dbo.Tests (
    test_id INT IDENTITY(1,1) PRIMARY KEY,
    user_id INT NOT NULL,
    test_level VARCHAR(5) NOT NULL,
    total_score INT NOT NULL DEFAULT 0,
    start_time DATETIME2 DEFAULT SYSDATETIME(),
    end_time DATETIME2 DEFAULT SYSDATETIME(),
    CONSTRAINT fk_tests_user
        FOREIGN KEY (user_id) REFERENCES dbo.Users(user_id)
        ON DELETE CASCADE
        ON UPDATE CASCADE
);
GO

-- ----------------------------------------------------------------------------
-- 4. Test_Details（作答明細中介表，打散 Tests 與 Questions 之 M:N 關聯）
-- ----------------------------------------------------------------------------
CREATE TABLE dbo.Test_Details (
    detail_id INT IDENTITY(1,1) PRIMARY KEY,
    test_id INT NOT NULL,
    question_id INT NOT NULL,
    user_choice CHAR(1) NOT NULL,
    is_correct BIT NOT NULL,
    CONSTRAINT fk_details_test
        FOREIGN KEY (test_id) REFERENCES dbo.Tests(test_id)
        ON DELETE CASCADE
        ON UPDATE CASCADE,
    CONSTRAINT fk_details_question
        FOREIGN KEY (question_id) REFERENCES dbo.Questions(question_id)
        ON DELETE NO ACTION
        ON UPDATE CASCADE
);
GO

